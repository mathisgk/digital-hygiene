def _positions(n_total, seed=107):
    """Balanced answer positions: equal counts of 0..3, never three in a row."""
    base = [i % 4 for i in range(n_total)]
    rng = random.Random(seed)
    while True:
        rng.shuffle(base)
        if all(not (base[i] == base[i+1] == base[i+2]) for i in range(len(base) - 2)):
            return base

_ORDER = sorted(BANK)
_POS = dict(zip([(n, i) for n in _ORDER for i in range(len(BANK[n]))], _positions(sum(len(BANK[n]) for n in _ORDER))))

def build(n):
    out = []
    for i, (q, right, wrong, exp) in enumerate(BANK[n]):
        pos = _POS[(n, i)]
        opts = list(wrong)
        opts.insert(pos, right)
        out.append((q, opts, pos, exp))
    return out
